import math

import unreal


# Idle for the four Meshy NPCs is retargeted from the Mannequin MM_Idle; talk is that idle
# with a head nod, torso sway and hand gestures layered on, until real talk clips exist.
ANIM_DIR = "/Game/SilkVillage/NPC/Anim"
SOURCE_RIG = "/Game/Character/Animation/IK_AutoGeneratedSource"  # SK_Manny
SOURCE_MESH = "/Game/Shared/Mannequins/Meshes/SK_Manny"
SOURCE_IDLE = "/Game/Characters/Mannequins/Anims/Unarmed/MM_Idle"

NPC_MESHES = {
    "Elder": "/Game/MeshyImports/Import_20261022_153724/Elder_in_Traditional_Attire_Import0002",
    "Blue": "/Game/MeshyImports/Import_20261022_153551/Man_in_Blue_Traditional_Attire_Import0001",
    "Highland": "/Game/MeshyImports/Import_20261022_153747/Vibrant_Highland_Heritage_Import0003",
    "Crimson": "/Game/MeshyImports/Import_20261022_153843/The_Crimson_Sash_Import0004",
}

# bone: (axis, degrees, cycles over the clip, phase). Cycles are whole numbers so the clip loops.
TALK_LAYERS = {
    "Head": [((0, 1, 0), 7.0, 6, 0.0), ((0, 0, 1), 4.0, 2, 0.6)],
    "Neck": [((0, 1, 0), 3.0, 6, 0.3)],
    "Spine": [((1, 0, 0), 2.0, 2, 0.0), ((0, 0, 1), 2.5, 1, 1.2)],
    "RightArm": [((0, 1, 0), 10.0, 2, 0.0)],
    "RightForeArm": [((0, 0, 1), 22.0, 4, 0.4)],
    "RightHand": [((1, 0, 0), 15.0, 4, 0.9)],
    "LeftForeArm": [((0, 0, 1), -12.0, 2, 2.1)],
    "LeftHand": [((1, 0, 0), -10.0, 3, 1.5)],
}

asset_tools = unreal.AssetToolsHelpers.get_asset_tools()
eal = unreal.EditorAssetLibrary


def recreate(name, asset_class, factory):
    path = "{}/{}".format(ANIM_DIR, name)
    if eal.does_asset_exist(path):
        eal.delete_asset(path)
    return asset_tools.create_asset(name, ANIM_DIR, asset_class, factory)


def build_rig(key, mesh):
    rig = recreate("IK_NPC_" + key, unreal.IKRigDefinition, unreal.IKRigDefinitionFactory())
    controller = unreal.IKRigController.get_controller(rig)
    controller.set_skeletal_mesh(mesh)
    if not controller.apply_auto_generated_retarget_definition():
        raise RuntimeError("Auto retarget definition failed for " + key)
    return rig


def build_retargeter(key, target_rig, target_mesh):
    rtg = recreate("RTG_NPC_" + key, unreal.IKRetargeter, unreal.IKRetargetFactory())
    controller = unreal.IKRetargeterController.get_controller(rtg)
    controller.set_ik_rig(unreal.RetargetSourceOrTarget.SOURCE, unreal.load_asset(SOURCE_RIG))
    controller.set_ik_rig(unreal.RetargetSourceOrTarget.TARGET, target_rig)
    controller.set_preview_mesh(unreal.RetargetSourceOrTarget.SOURCE, unreal.load_asset(SOURCE_MESH))
    controller.set_preview_mesh(unreal.RetargetSourceOrTarget.TARGET, target_mesh)
    controller.add_default_ops()
    controller.assign_ik_rig_to_all_ops(unreal.RetargetSourceOrTarget.TARGET, target_rig)
    controller.auto_map_chains(unreal.AutoMapChainType.FUZZY, True)
    # Meshy binds in T-pose, Manny in A-pose: align the target retarget pose to the source.
    controller.create_retarget_pose("NPC_Aligned", unreal.RetargetSourceOrTarget.TARGET)
    controller.auto_align_all_bones(unreal.RetargetSourceOrTarget.TARGET)
    eal.save_loaded_asset(rtg)
    return rtg


def retarget_idle(key, target_mesh, rtg):
    name = "AS_NPC_Idle_" + key
    dest = "{}/{}".format(ANIM_DIR, name)
    if eal.does_asset_exist(dest):
        eal.delete_asset(dest)
    source = unreal.AssetRegistryHelpers.get_asset_registry().get_asset_by_object_path(SOURCE_IDLE + ".MM_Idle")
    results = unreal.IKRetargetBatchOperation.duplicate_and_retarget(
        [source], unreal.load_asset(SOURCE_MESH), target_mesh, rtg, "", "", "", "_NPC_" + key, False)
    produced = [r for r in results if str(r.asset_class_path.asset_name) == "AnimSequence"]
    if not produced:
        raise RuntimeError("Retarget produced no AnimSequence for " + key)
    eal.rename_asset(str(produced[0].package_name), dest)
    idle = unreal.load_asset(dest)
    idle.set_editor_property("enable_root_motion", False)
    restore_reference_translation_scale(idle, target_mesh)
    eal.save_loaded_asset(idle)
    return idle


def restore_reference_translation_scale(seq, mesh):
    """Meshy rigs carry a x100 scale on the root bone (metre armature). The retargeter writes
    unit scale and loses bone offsets, collapsing the body, so keep only retargeted rotations
    and take translation and scale from the mesh's reference pose."""
    ref_pose = unreal.AnimPoseExtensions.get_reference_pose(mesh.skeleton)
    num_keys = unreal.AnimationLibrary.get_num_keys(seq)
    controller = seq.controller
    controller.open_bracket("Restore reference translation and scale")
    for bone in unreal.AnimationLibrary.get_animation_track_names(seq):
        ref = unreal.AnimPoseExtensions.get_bone_pose(ref_pose, bone, unreal.AnimPoseSpaces.LOCAL)
        rotations = [unreal.AnimationLibrary.get_bone_pose_for_frame(seq, bone, f, False).rotation
                     for f in range(num_keys)]
        controller.set_bone_track_keys(bone, [ref.translation] * num_keys, rotations, [ref.scale3d] * num_keys, True)
    controller.close_bracket()


def layer_talk(key, idle):
    dest = "{}/AS_NPC_Talk_{}".format(ANIM_DIR, key)
    if eal.does_asset_exist(dest):
        eal.delete_asset(dest)
    talk = eal.duplicate_asset(idle.get_path_name().split(".")[0], dest)
    controller = talk.controller
    num_keys = unreal.AnimationLibrary.get_num_keys(talk)
    # Track names come back lower-cased; FName lookups are case-insensitive.
    bones = set(str(b).lower() for b in unreal.AnimationLibrary.get_animation_track_names(talk))
    controller.open_bracket("NPC talk layer")
    for bone, layers in TALK_LAYERS.items():
        if bone.lower() not in bones:
            unreal.log_warning("Talk layer skipped, no track for {}".format(bone))
            continue
        positions, rotations, scales = [], [], []
        for frame in range(num_keys):
            base = unreal.AnimationLibrary.get_bone_pose_for_frame(talk, bone, frame, False)
            t = frame / max(1, num_keys - 1)
            delta = unreal.Quat(0.0, 0.0, 0.0, 1.0)  # Quat() is all zeros, not identity
            for axis, degrees, cycles, phase in layers:
                half = 0.5 * math.radians(degrees * math.sin(2.0 * math.pi * cycles * t + phase))
                s = math.sin(half)
                delta = delta.multiply(unreal.Quat(axis[0] * s, axis[1] * s, axis[2] * s, math.cos(half)))
            positions.append(base.translation)
            rotations.append(base.rotation.multiply(delta))  # rotate about the bone's own axes
            scales.append(base.scale3d)
        controller.set_bone_track_keys(bone, positions, rotations, scales, True)
    controller.close_bracket()
    eal.save_loaded_asset(talk)
    return talk


def main():
    for key, mesh_path in NPC_MESHES.items():
        mesh = unreal.load_asset(mesh_path)
        rig = build_rig(key, mesh)
        rtg = build_retargeter(key, rig, mesh)
        idle = retarget_idle(key, mesh, rtg)
        talk = layer_talk(key, idle)
        print("NPC_ANIM {} idle={} talk={} length={:.2f}s".format(
            key, idle.get_path_name(), talk.get_path_name(), idle.get_play_length()))
    probe = ANIM_DIR + "/IK_Tmp_Probe"
    if eal.does_asset_exist(probe):
        eal.delete_asset(probe)


main()
